#!/usr/bin/env python3
"""Regenerate `requirements.lock` — the pinned Python dependency set CI installs.

I20 was "no Python lockfile": the project declared ranges, so two CI runs a
week apart could resolve different versions and a green pipeline on Monday
could be red on Friday for reasons that have nothing to do with the code.

This resolves `.[dev]` from PyPI with pip's own resolver (no second resolver
to keep in sync) and writes the exact resolved set, excluding the project
itself (installed editable from the checkout).

Usage:
    python scripts/lock.py            # write requirements.lock
    python scripts/lock.py --check    # verify the committed lock is current

`--check` is the CI gate: it fails when the committed lock no longer matches
what the declared ranges resolve to, so a range bump can never land without
the lock being refreshed in the same commit.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements.lock"
PROJECT = "procurementos-agent"


def _canonical(name: str) -> str:
    """PEP 503 normalised distribution name.

    PyPI is indifferent to `pip-audit`, `pip_audit` and `Pip.Audit`; the
    resolver may report any of them. Normalising on both sides is what
    stops a check from failing over a spelling.
    """
    from packaging.utils import canonicalize_name

    return str(canonicalize_name(name))


def resolve() -> list[str]:
    """Ask pip to resolve `.[dev]` from scratch and return pinned requirements."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--quiet",
            "--report",
            str(report),
            ".[dev]",
        ]
        proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)  # noqa: S603
        if proc.returncode != 0:
            sys.stderr.write(proc.stdout + proc.stderr)
            raise SystemExit(f"pip resolution failed (exit {proc.returncode})")
        data = json.loads(report.read_text(encoding="utf-8"))
    pins = {
        f"{_canonical(item['metadata']['name'])}=={item['metadata']['version']}"
        for item in data.get("install", [])
        if _canonical(item["metadata"]["name"]) != _canonical(PROJECT)
    }
    return sorted(pins, key=str.lower)


def render(pins: list[str]) -> str:
    header = [
        "# ProcurementOS-Agent — pinned Python dependency set.",
        "#",
        "# Generated by `python scripts/lock.py`. Do not edit by hand:",
        "# `python scripts/lock.py --check` in CI fails when this file is stale.",
        "#",
        "# Install with:  pip install -r requirements.lock",
        "",
    ]
    return "\n".join(header + pins) + "\n"


def _declared_requirements() -> list[str]:
    """Every requirement pyproject declares, runtime and dev."""
    import tomllib

    with (ROOT / "pyproject.toml").open("rb") as fh:
        data = tomllib.load(fh)
    project = data.get("project", {})
    out = list(project.get("dependencies", []))
    for extra in project.get("optional-dependencies", {}).values():
        out.extend(extra)
    return out


def _locked_pins() -> dict[str, str]:
    """The pins in requirements.lock, by distribution name."""
    pins: dict[str, str] = {}
    if not LOCK.exists():
        return pins
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        name, _, version = line.partition("==")
        pins[_canonical(name.strip())] = version.strip()
    return pins


def check_consistent() -> list[str]:
    """The lock must pin a version that satisfies every declared range.

    The check is *consistency*, not equality with a fresh resolution. A
    lockfile whose check re-resolves "latest" on every run breaks the
    moment a new version is published — which is a property of PyPI, not
    of this repository, and would make CI fail for no reason. What must
    hold is that the lock still covers the declared ranges: a range bump
    that does not refresh the lock is the mistake worth catching.
    """
    from packaging.requirements import Requirement
    from packaging.version import Version

    pins = _locked_pins()
    problems: list[str] = []
    for raw in _declared_requirements():
        req = Requirement(raw)
        name = _canonical(req.name)
        if name not in pins:
            problems.append(f"{req.name} is declared but not pinned in requirements.lock")
            continue
        version = Version(pins[name])
        if req.specifier and not req.specifier.contains(version, prereleases=True):
            problems.append(
                f"requirements.lock pins {req.name}=={pins[name]}, which does not "
                f"satisfy the declared range {req.specifier}"
            )
    return problems


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the lock is stale")
    args = ap.parse_args()

    if args.check:
        problems = check_consistent()
        if problems:
            print("requirements.lock is STALE — run: python scripts/lock.py")
            for p in problems:
                print(f"  - {p}")
            raise SystemExit(1)
        pins = _locked_pins()
        print(f"requirements.lock is current ({len(pins)} pins, consistent with pyproject)")
        return

    resolved = resolve()
    LOCK.write_text(render(resolved), encoding="utf-8")
    print(f"wrote {LOCK.relative_to(ROOT)} ({len(resolved)} pins)")


if __name__ == "__main__":
    main()
